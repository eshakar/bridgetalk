logger = logging.getLogger("bridgetalk.routes")

router = APIRouter(prefix="/api/meetings", tags=["meetings"])


async def optional_repository(request: Request) -> MeetingRepository | None:
    db = await request.app.state.mongo.get_db()
    return MeetingRepository(db) if db is not None else None


async def require_repository(request: Request) -> MeetingRepository:
    repository = await optional_repository(request)
    if repository is None:
        raise DatabaseUnavailableError()
    return repository


def _fallback_demo() -> MeetingDetail:
    """The built-in sample, clearly marked as not persisted."""
    return MeetingDetail(**SAMPLE_MEETING.model_dump(), persisted=False)


async def _stored_transcript(repository: MeetingRepository, meeting_id: str) -> TranscriptPayload:
    meeting = await repository.get_meeting(parse_object_id(meeting_id))
    if meeting is None:
        raise NotFoundError("Meeting not found.")
    return TranscriptPayload(title=meeting.title, speakers=meeting.speakers, segments=meeting.segments)


# Roughly 2.5 spoken words per second; used when the user gives no timestamps.
_WORDS_PER_SECOND = 2.5


def _speaking_seconds(text: str) -> float:
    return max(3.0, round(len(text.split()) / _WORDS_PER_SECOND, 1))


def _build_meeting(body: MeetingCreate, translations: dict[str, dict[str, str]]) -> Meeting:
    speakers = [
        {"id": f"p{i + 1}", "name": p.name.strip(), "role": p.role.strip(), "primary_language": p.primary_language}
        for i, p in enumerate(body.participants)
    ]
    segments = []
    clock = 0.0
    for i, line in enumerate(body.lines):
        segment_id = f"s{i + 1}"
        start = max(line.start_seconds if line.start_seconds is not None else clock, clock)
        end = start + _speaking_seconds(line.text)
        original = line.text.strip()
        # The user's own words always win over a model translation of the same language.
        text = {**translations.get(segment_id, {}), line.language: original}
        segments.append(
            {
                "id": segment_id,
                "speaker_id": speakers[line.speaker]["id"],
                "start_seconds": start,
                "end_seconds": end,
                "original_language": line.language,
                "text": text,
            }
        )
        clock = end
    used = {code for segment in segments for code in segment["text"]}
    translated = bool(translations)
    return Meeting(
        id="new",
        title=body.title.strip(),
        description=body.description.strip(),
        status="completed",
        date=body.date or date.today().isoformat(),
        duration_seconds=int(clock),
        is_simulated=False,
        source_note=(
            "Transcript entered by a user. Translations generated by Google Gemini; check important details against the original."
            if translated
            else "Transcript entered by a user. Lines are shown in their original language only."
        ),
        languages=[language for language in SAMPLE_MEETING.languages if language.code in used],
        speakers=speakers,
        segments=segments,
    )


@router.post("", response_model=MeetingDetail, status_code=201)
async def create_meeting(body: MeetingCreate, request: Request) -> MeetingDetail:
    """Create a meeting from user input. Lines are translated with Gemini when it is configured."""
    repository = await require_repository(request)
    translations: dict[str, dict[str, str]] = {}
    if body.translate:
        lines = [(f"s{i + 1}", line.language, line.text.strip()) for i, line in enumerate(body.lines)]
        translations = await run_in_threadpool(translate_lines, lines)
        translations = {k: {c: t for c, t in v.items() if c in LANGUAGE_CODES} for k, v in translations.items()}
    meeting_id = await repository.create_meeting(_build_meeting(body, translations))
    detail = await repository.get_meeting_detail(meeting_id)
    if detail is None:
        raise NotFoundError("Meeting not found.")
    return detail


@router.get("", response_model=list[MeetingSummary])
async def list_meetings(repository: MeetingRepository = Depends(require_repository)) -> list[MeetingSummary]:
    return await repository.list_meetings()


@router.get("/demo", response_model=MeetingDetail)
async def get_demo_meeting(request: Request) -> MeetingDetail:
    """The seeded demo meeting from MongoDB, or the built-in sample when the database is down."""
    repository = await optional_repository(request)
    if repository is None:
        return _fallback_demo()
    try:
        detail = await repository.get_meeting_detail(await repository.get_demo_meeting_id())
    except PyMongoError as exc:
        logger.warning("Demo meeting read failed (%s); serving fallback.", type(exc).__name__)
        return _fallback_demo()
    return detail or _fallback_demo()


@router.post("/demo/reset", response_model=MeetingDetail)
async def reset_demo_meeting(request: Request) -> MeetingDetail:
    """Clear saved insights and questions for the demo meeting. The transcript is kept."""
    repository = await optional_repository(request)
    if repository is None:
        return _fallback_demo()
    meeting_id = await repository.get_demo_meeting_id()
    await repository.clear_insights_and_questions(meeting_id)
    detail = await repository.get_meeting_detail(meeting_id)
    if detail is None:
        raise NotFoundError("Meeting not found.")
    return detail


@router.post("/{meeting_id}/reset", response_model=MeetingDetail)
async def reset_meeting(meeting_id: str, request: Request) -> MeetingDetail:
    """Clear a meeting's saved insights and questions. The transcript is kept."""
    object_id = parse_object_id(meeting_id)
    repository = await require_repository(request)
    await repository.clear_insights_and_questions(object_id)
    detail = await repository.get_meeting_detail(object_id)
    if detail is None:
        raise NotFoundError("Meeting not found.")
    return detail


@router.delete("/{meeting_id}", status_code=204)
async def delete_meeting(meeting_id: str, request: Request) -> Response:
    object_id = parse_object_id(meeting_id)
    repository = await require_repository(request)
    if not await repository.delete_meeting(object_id):
        raise NotFoundError("Meeting not found, or it is the protected sample meeting.")
    return Response(status_code=204)


@router.get("/{meeting_id}", response_model=MeetingDetail)
async def get_meeting(meeting_id: str, request: Request) -> MeetingDetail:
    object_id = parse_object_id(meeting_id)
    repository = await require_repository(request)
    detail = await repository.get_meeting_detail(object_id)
    if detail is None:
        raise NotFoundError("Meeting not found.")
    return detail


@router.post("/analyze", response_model=AnalysisResult)
async def analyze(body: AnalyzeRequest, request: Request) -> AnalysisResult:
    """Analyse a stored meeting (and save the result) or an inline transcript (not saved)."""
    if not body.meeting_id:
        return await run_in_threadpool(analyze_meeting, body.inline_transcript())
    object_id = parse_object_id(body.meeting_id)
    repository = await require_repository(request)
    transcript = await _stored_transcript(repository, body.meeting_id)
    result = await run_in_threadpool(analyze_meeting, transcript)
    return await repository.save_insights(object_id, result)


@router.post("/ask", response_model=AnswerResult)
async def ask(body: AskRequest, request: Request) -> AnswerResult:
    """Answer from the transcript only. Stored meetings also save the question and answer."""
    question = body.question.strip()
    if not body.meeting_id:
        return await run_in_threadpool(answer_question, body.inline_transcript(), question)
    object_id = parse_object_id(body.meeting_id)
    repository = await require_repository(request)
    transcript = await _stored_transcript(repository, body.meeting_id)
    result = await run_in_threadpool(answer_question, transcript, question)
    await repository.save_question(object_id, question, result)
    return result.model_copy(update={"persisted": True})


@router.patch("/{meeting_id}/action-items/{action_item_id}", response_model=ActionItem)
async def update_action_item(meeting_id: str, action_item_id: str, body: ActionItemUpdate, request: Request) -> ActionItem:
    object_id = parse_object_id(meeting_id)
    repository = await require_repository(request)
    item = await repository.update_action_item_status(object_id, action_item_id[:40], body.status)
    if item is None:
        raise NotFoundError("Action item not found for this meeting.")
    return item
